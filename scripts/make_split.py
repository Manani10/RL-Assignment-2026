"""Create the frozen development / held-out game split — OWNER: Member 1.

Deterministic (fixed seed) so anyone can regenerate and verify it. Run ONCE,
commit configs/splits.json, and never tune anything on the held-out games
(assignment §4.3: avoid claiming generalisation from repeated testing).

Usage
    python scripts/make_split.py --from-inspection results/inspection/games.json --held-out-frac 0.4
    python scripts/make_split.py --games ls20 ft09 vc33 ... --held-out-frac 0.4
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import random
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "configs" / "splits.json"


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--games", nargs="*")
    p.add_argument("--from-inspection")
    p.add_argument("--held-out-frac", type=float, default=0.4)
    p.add_argument("--seed", type=int, default=2026)
    p.add_argument("--force", action="store_true", help="overwrite an existing non-empty split")
    a = p.parse_args()

    if a.from_inspection:
        data = json.loads(Path(a.from_inspection).read_text())
        games = [r["game_id"] for r in data["probe"] if "error" not in r]
    else:
        games = list(a.games or [])
    games = sorted(set(games))
    if len(games) < 2:
        raise SystemExit("need at least 2 games")

    if OUT.exists() and not a.force:
        cur = json.loads(OUT.read_text())
        if cur.get("dev") or cur.get("held_out"):
            raise SystemExit("splits.json already filled — the split is frozen. Use --force only if the team agrees.")

    rng = random.Random(a.seed)
    shuffled = games[:]
    rng.shuffle(shuffled)
    k = max(1, round(len(games) * a.held_out_frac))
    split = {
        "_note": "FROZEN. Generated by scripts/make_split.py. Never tune on held_out.",
        "seed": a.seed,
        "created": dt.date.today().isoformat(),
        "dev": sorted(shuffled[k:]),
        "held_out": sorted(shuffled[:k]),
    }
    OUT.write_text(json.dumps(split, indent=2) + "\n")
    print(json.dumps(split, indent=2))


if __name__ == "__main__":
    main()
