"""Bundle our `arcrl` package + the Kaggle bridge into ONE self-contained file.

Why: the official Kaggle starter packages only `agent/my_agent.py` into the
submission notebook — any other local module we import would be missing on
Kaggle. This script embeds every `src/arcrl/**/*.py` file as a string and
installs an in-memory import hook, so `import arcrl...` works inside the
single file.

Usage
    python scripts/bundle_agent.py --agent dqn --out build/my_agent.py
    python scripts/bundle_agent.py --agent dqn --click-mode objects --prune-noops   # with the shared improvement
    cp build/my_agent.py ../ARC-AGI-3-Kaggle-Starter/agent/my_agent.py
    (cd ../ARC-AGI-3-Kaggle-Starter && make play-local && make submit)

The chosen agent name and action cap are baked into the file, and the bundle
records the git commit so every Kaggle submission maps to exact code.
"""
from __future__ import annotations

import argparse
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"

LOADER = '''
# ---------------------------------------------------------------------------
# In-memory package loader (generated by scripts/bundle_agent.py — do not edit)
# ---------------------------------------------------------------------------
import importlib.abc as _abc
import importlib.util as _util
import sys as _sys

_ARCRL_SOURCES = {sources}


class _ArcrlFinder(_abc.MetaPathFinder, _abc.Loader):
    def find_spec(self, name, path=None, target=None):
        if name in _ARCRL_SOURCES:
            is_pkg = _ARCRL_SOURCES[name][0]
            return _util.spec_from_loader(name, self, is_package=is_pkg)
        return None

    def create_module(self, spec):
        return None

    def exec_module(self, module):
        is_pkg, src = _ARCRL_SOURCES[module.__name__]
        if is_pkg:
            module.__path__ = []
        exec(compile(src, "<arcrl:" + module.__name__ + ">", "exec"), module.__dict__)


if not any(isinstance(f, _ArcrlFinder) for f in _sys.meta_path):
    _sys.meta_path.insert(0, _ArcrlFinder())
'''


def collect_sources() -> dict[str, tuple[bool, str]]:
    out = {}
    for path in sorted((SRC / "arcrl").rglob("*.py")):
        rel = path.relative_to(SRC).with_suffix("")
        parts = list(rel.parts)
        is_pkg = parts[-1] == "__init__"
        if is_pkg:
            parts = parts[:-1]
        out[".".join(parts)] = (is_pkg, path.read_text())
    return out


def git_commit() -> str:
    try:
        return subprocess.check_output(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, text=True).strip()
    except Exception:
        return "unknown"


def build(agent: str, max_actions: int, out: Path, click_mode: str = "grid", prune_noops: bool = False) -> Path:
    bridge = (ROOT / "kaggle" / "my_agent.py").read_text()
    # bake configuration into the bridge
    bridge = bridge.replace('os.environ.get("ARCRL_AGENT", "random")', f'os.environ.get("ARCRL_AGENT", "{agent}")')
    bridge = bridge.replace('os.environ.get("ARCRL_MAX_ACTIONS", "5000")',
                            f'os.environ.get("ARCRL_MAX_ACTIONS", "{max_actions}")')
    bridge = bridge.replace('os.environ.get("ARCRL_CLICK_MODE", "grid")', f'os.environ.get("ARCRL_CLICK_MODE", "{click_mode}")')
    bridge = bridge.replace('os.environ.get("ARCRL_PRUNE_NOOPS", "0")', f'os.environ.get("ARCRL_PRUNE_NOOPS", "{int(prune_noops)}")')
    # move `from __future__` (must be first statement) to the very top
    future = "from __future__ import annotations\n"
    bridge = bridge.replace(future, "", 1)
    header = (f'"""AUTO-GENERATED single-file agent. agent={agent} click_mode={click_mode} prune_noops={prune_noops} max_actions={max_actions} '
              f'commit={git_commit()}\nSource: kaggle/my_agent.py + src/arcrl (bundled). Do not edit by hand."""\n')
    text = header + future + LOADER.replace("{sources}", repr(collect_sources())) + "\n" + bridge
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    compile(text, str(out), "exec")  # fail fast on syntax errors
    return out


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--agent", default="random")
    p.add_argument("--max-actions", type=int, default=5000)
    p.add_argument("--out", default="build/my_agent.py")
    p.add_argument("--click-mode", default="grid", choices=["grid", "objects"])
    p.add_argument("--prune-noops", action="store_true")
    a = p.parse_args()
    path = build(a.agent, a.max_actions, ROOT / a.out, a.click_mode, a.prune_noops)
    print(f"wrote {path} ({path.stat().st_size // 1024} KB) agent={a.agent} commit={git_commit()}")


if __name__ == "__main__":
    main()
